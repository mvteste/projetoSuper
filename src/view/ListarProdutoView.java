    private void preencherTabela(java.util.List<model.Produto> lista) {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0); // Zera a tabela

        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy");

        for (model.Produto p : lista) {
            // 1. Prepara a data
            String dataFormatada = "";
            if (p.getDataVencimento() != null) {
                dataFormatada = sdf.format(p.getDataVencimento());
            }
            
            // 2. Prepara a categoria
            String nomeCategoria = "Sem Categoria";
            if (p.getCategoria() != null) {
                nomeCategoria = p.getCategoria().getNome();
            }
            
            // 3. Prepara o preço com R$
            String precoFormatado = String.format("R$ %.2f", p.getPreco());

            // 4. Adiciona na tabela EXATAMENTE na ordem que está na sua tela!
            modelo.addRow(new Object[]{
                p.getId(),          // 1ª Coluna: ID (A que criamos agora)
                p.getNome(),        // 2ª Coluna: Produto
                dataFormatada,      // 3ª Coluna: Data V.
                nomeCategoria,      // 4ª Coluna: Categoria
                precoFormatado      // 5ª Coluna: Preço
            });
        }
    }
