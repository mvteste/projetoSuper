    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int linhaSelecionada = jTable1.getSelectedRow();
        
    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto para excluir!");
        return;
    }
        
    int confirmacao = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Deseja realmente excluir este produto?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
        
    if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
       int idProduto = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());
            
        controller.excluirProduto(idProduto); // Exclui no banco
        preencherTabela(controller.listarProdutos()); // Recarrega a tabela
        javax.swing.JOptionPane.showMessageDialog(this, "Produto excluído com sucesso!");
    }
    }//GEN-LAST:event_jButton3ActionPerformed


