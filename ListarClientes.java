    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int linhaSelecionada = jTable1.getSelectedRow();
        // verificar se alguma linha foi selecionada
        if (linhaSelecionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um cliente para excluir");
            return;
        }
        int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir este cliente?",
                "Confirmar exclusao",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
            repositorio.listar().remove(linhaSelecionada);
            carregarTabela();
    }//GEN-LAST:event_jButton1ActionPerformed
    }
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String textoPesquisa = jTextField1.getText().trim().toLowerCase();
        javax.swing.table.DefaultTableModel modelo
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        for(Clientes c : repositorio.listar()){
            if(c.getNome().toLowerCase().contains(textoPesquisa)){
                modelo.addRow(new Object[]{
                        c.getNome(),
                        c.getNascimento(),
                        c.getCpf()
                                });
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

