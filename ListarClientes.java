    private void carregarTabela() {
        javax.swing.table.DefaultTableModel modelo
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0);

        for (Clientes c : repositorio.listar()) {
            modelo.addRow(new Object[]{
                c.getNome(),
                c.getNascimento(),
                c.getCpf()
            });
        }

        modelo.addTableModelListener(e -> {
            int linha = e.getFirstRow();
            int coluna = e.getColumn();

            if (linha >= 0 && coluna >= 0) {
                Clientes c = repositorio.listar().get(linha);
                switch (coluna) {
                    case 0 ->
                        c.setNome((String) modelo.getValueAt(linha, coluna));
                    case 1 ->
                        c.setNascimento((String) modelo.getValueAt(linha, coluna));
                    case 2 ->
                        c.setCpf((String) modelo.getValueAt(linha, coluna));
                }
            }
        });
    }

